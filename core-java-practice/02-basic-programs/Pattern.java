class Pattern
{ 
    /**
 * Prints a shrinking star pattern using one println statement per line.
 * Concept: printing text line by line. Each line is written by hand here,
 * so nested loops (used in the control flow topic) can later do the same job.
 */
 public static void main(String[]a)
 {
  System.out.println("******");
  System.out.println("****");
  System.out.println("**");
  System.out.println("*");
 }
}
