class Division
{
    /**
 * Divides one int by another and prints the result.
 * Concept: integer division. When both numbers are int, the result is also an int,
 * so any decimal part is dropped (for example, 15 / 7 gives 2, not 2.14).
 */
 public static void main(String[]args)
 {
  int a=7;
  int b=14;

  // b is divided by a, so this prints 2
  System.out.println(b/a);
 
 }


}